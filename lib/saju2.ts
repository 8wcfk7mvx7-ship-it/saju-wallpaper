// ─── 금수쌍청(金水雙淸) 격국 DB ─────────────────────────────────────────────
// 경금/신금 일간이 해자월에 태어나고 수기 식상이 강하며 화기 관성으로 조후된 고귀한 격
export interface GumsuResult {
  hasGumsu: boolean;
  level: "완전체" | "미완성" | "해당없음";
  ilganType: "경" | "신" | null;
  missingConditions: string[];
  desc: string;
  careerHint: string;
}

// 조토(燥土): 미·술 — 수를 극제해 금수쌍청 방해
const JOTO = new Set(["미", "술"]);
// 녹왕지(祿旺地): 경금→신유, 신금→유
const NOKWANG: Record<string, string[]> = { 경: ["신", "유", "진"], 신: ["유", "축"] };
// 해자월 = 겨울 수왕절
const HAEJA_MONTH = new Set(["해", "자"]);

export function detectGumsuSangcheong(
  ilgan: string,
  monthJj: string,
  allCg: string[],
  allJj: string[]
): GumsuResult {
  const isKyeong = ilgan === "경";
  const isShin = ilgan === "신";
  if (!isKyeong && !isShin) {
    return { hasGumsu: false, level: "해당없음", ilganType: null, missingConditions: [], desc: "", careerHint: "" };
  }
  const ilganType = isKyeong ? "경" : "신";
  const missing: string[] = [];

  // 조건1: 해자월 출생
  if (!HAEJA_MONTH.has(monthJj)) missing.push("해자월(11~12월) 출생이 아님");

  // 조건2: 일간 뿌리(녹왕지)
  const hasRoot = NOKWANG[ilganType].some(j => allJj.includes(j));
  if (!hasRoot) missing.push("일간 녹왕지(뿌리) 부족");

  // 조건3: 조토(미·술) 방해 없음
  const hasJoto = allJj.some(j => JOTO.has(j));
  if (hasJoto) missing.push("조토(미·술)가 수기를 방해");

  // 조건4: 수 천간 투출 (경→임수, 신→계수)
  const needWater = isKyeong ? "임" : "계";
  const hasWater = allCg.includes(needWater);
  if (!hasWater) missing.push(`${needWater}수 천간 투출 없음`);

  // 조건5: 화기 관성 (경→병화, 신→정화) — 조후 역할
  const needFire = isKyeong ? "병" : "정";
  const hasFire = allCg.includes(needFire) || allJj.some(j => ["사", "오"].includes(j));
  if (!hasFire) missing.push(`화기(${needFire}화) 관성 조후 없음`);

  const hasGumsu = missing.length === 0;
  const level = hasGumsu ? "완전체" : missing.length <= 2 ? "미완성" : "해당없음";

  const desc = hasGumsu
    ? `${ilganType}금 일간이 해자월에 뿌리를 두고 ${needWater}수가 천간에 투출하며 ${needFire}화 관성이 조후해주는 금수쌍청 완전체예요. 차갑고 날카로운 금(金)이 맑은 수(水)로 윤택해지고, 화(火)의 온기로 그 역량이 빛을 발하는 구조입니다. 뛰어난 재능과 총명함, 맑고 고귀한 기운을 타고났어요.`
    : level === "미완성"
    ? `${ilganType}금 일간의 금수쌍청 기질이 일부 갖춰진 구조예요. ${missing.join(", ")}이 아쉬운 부분이에요. 조건이 완전히 갖춰지진 않았지만, 금수의 총명하고 냉철한 기운은 충분히 살아있어요.`
    : "";

  const careerHint = hasGumsu
    ? "예술·기술·학문·언론·법조 등 정밀한 사고력과 표현력이 요구되는 분야에서 두각을 나타내기 쉬워요. 타인의 도움보다 자신의 역량으로 길을 개척하는 자영업·프리랜서·전문직 기질이 강합니다."
    : level === "미완성"
    ? "금수의 날카롭고 총명한 기질은 살아있어요. 전문성을 키우는 방향이 잘 맞아요."
    : "";

  return { hasGumsu, level, ilganType, missingConditions: missing, desc, careerHint };
}


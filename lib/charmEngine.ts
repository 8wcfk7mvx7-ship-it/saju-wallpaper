// ── 매력 점수 계산 ─────────────────────────────────────────────────────────────
export function calcCharmGrade(result: SajuResult): CharmGradeResult {
  const sinsalNames = result.sinsalList.map(s => s.name);
  const ilgan = result.pillarsDetail.day.cg;

  // 신살 점수
  let salScore = 0;
  for (const sal of SAL_CHARM_DB) {
    if (sinsalNames.includes(sal.key)) {
      salScore += sal.charmGrade;
    }
  }

  // 일간 점수
  const ilganScores: Record<string, number> = {
    갑: 6, 을: 6, 병: 8, 정: 5, 무: 5,
    기: 5, 경: 7, 신: 7, 임: 6, 계: 5,
  };
  const ilganScore = ilganScores[ilgan] || 5;

  // 기본 점수
  const base = 10;
  const total = base + salScore + ilganScore;

  // 등급 결정
  const gradeInfo = GRADE_LIST.find(g => total >= g.min) || GRADE_LIST[GRADE_LIST.length - 1];
  const topPercent = (gradeInfo.tMin + gradeInfo.tMax) / 2;

  return {
    total,
    grade: gradeInfo.g,
    label: gradeInfo.label,
    topPercent,
    color: gradeInfo.color,
    bg: gradeInfo.bg,
    emoji: gradeInfo.emoji,
    sc: gradeInfo.sc,
    desc: gradeInfo.desc,
    breakdown: { sal: salScore, ilgan: ilganScore, base },
  };
}


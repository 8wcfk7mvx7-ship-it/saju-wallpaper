function hashSeed(str: string): number {
  let h = 0;
  for (let i = 0; i < str.length; i++) h = (h * 31 + str.charCodeAt(i)) >>> 0;
  return h;
}

// 날짜 하나당 응답 하나 — 같은 날엔 누가 몇 번을 다시 불러도 같은 응답이 뜬다
// (오늘의 개운법과 같은 "오늘은 다 같은 하루" 방식).
export function getHeavenReply(dateKey: string): string {
  const seed = hashSeed(`heaven-${dateKey}`);
  return HEAVEN_REPLIES[seed % HEAVEN_REPLIES.length];
}

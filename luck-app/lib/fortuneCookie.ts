// 진짜 포춘쿠키처럼 순수 랜덤으로 동작한다.
export function getRandomFortune(exclude?: string): string {
  if (FORTUNE_COOKIE_MESSAGES.length <= 1) return FORTUNE_COOKIE_MESSAGES[0];
  let pick: string;
  do {
    pick = FORTUNE_COOKIE_MESSAGES[Math.floor(Math.random() * FORTUNE_COOKIE_MESSAGES.length)];
  } while (pick === exclude);
  return pick;
}
